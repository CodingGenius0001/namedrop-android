export function normalize(text) {
  return text.trim().toUpperCase().normalize('NFD').replace(/\p{M}+/gu, '')
    .replace(/[\u2019\u2018]/g, "'").replace(/\s+/g, ' ');
}

export function canRender(text) {
  const n = normalize(text);
  return n.length > 0 && [...n].every((c) => c in GLYPHS);
}

/** One line of cells: {columns, cells: [[col,row],...]} */
export function layout(text) {
  const n = [...normalize(text)];
  const cells = [];
  let x = 0;
  n.forEach((ch, i) => {
    const g = GLYPHS[ch] || GLYPHS[' '];
    for (let r = 0; r < ROWS; r++) for (let c = 0; c < g[r].length; c++) if (g[r][c] === '#') cells.push([x + c, r]);
    x += g[0].length;
    if (i !== n.length - 1) x += GAP;
  });
  return { columns: x, cells };
}
